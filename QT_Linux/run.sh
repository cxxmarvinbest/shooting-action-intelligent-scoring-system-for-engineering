#!/usr/bin/env bash
# ============================================================
# RK3588 Linux 桌面环境启动 Qt 客户端
# 默认连本机算法服务 127.0.0.1:8899（算法服务与本客户端同机）
# 用法：
#   ./run.sh
# 或指定远端算法服务：
#   LQ_QT_HOST=192.168.8.75 LQ_QT_PORT=8899 ./run.sh
# ============================================================
set -e
cd "$(dirname "$0")"

# 桌面环境通常自动选择 xcb；若黑屏/无窗口可手动指定平台插件
# export QT_QPA_PLATFORM=xcb

# 算法服务地址（可被环境变量覆盖，默认本机）
: "${LQ_QT_HOST:=127.0.0.1}"
: "${LQ_QT_PORT:=8899}"
export LQ_QT_HOST LQ_QT_PORT

exec python3 main.py
